namespace Popup.Models
{
    /*
     * 이미지 팝업 크기를 결정하는 방식을 정의한다.
     */
    public enum ImagePopupSizeMode
    {
        /*
         * 이미지 가로세로 비율을 확인하여
         * 가로형, 세로형, 정사각형 레이아웃에 맞는
         * 미리 정해진 팝업 크기를 사용한다.
         */
        Adaptive,

        /*
         * 불러온 이미지의 실제 표시 크기를 기준으로
         * 팝업 창의 너비와 높이를 계산한다.
         *
         * 이미지가 모니터보다 큰 경우에는
         * 화면 안에 들어오도록 자동으로 축소한다.
         */
        FitToImage
    }
}